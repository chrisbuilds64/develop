"""Units, the davfs2 secret and the nginx locations — rendered from the stage table, installed in place.

Per stage three units: the WebDAV mount of its team folder, its cockpit, its runner. Names carry the
stage (`pressroom-runner-test.service`), so `systemctl status 'pressroom-*'` tells the whole story.
The nginx snippet holds one `location` per prefixed stage; the vhost includes it once, by hand.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

from .config import Env, OpsError, Settings
from .shell import run
from .workspace import _render

log = logging.getLogger("pressroom-env")
SYSTEMD = Path("/etc/systemd/system")
LEGACY_UNITS = ("pressroom-runner.service", "pressroom-cockpit.service")   # the single-stage units from 2026-10-13


def mount_unit_name(mount: Path) -> str:
    return run(["systemd-escape", "-p", "--suffix=mount", str(mount)], quiet=True).stdout.strip()


def unit_names(env: Env) -> dict[str, str]:
    return {"mount": mount_unit_name(env.mount), "cockpit": f"pressroom-cockpit-{env.name}.service",
            "runner": f"pressroom-runner-{env.name}.service"}


def ensure_davfs_secret(settings: Settings, env: Env, dav_url: str) -> None:
    """The runner's app password, copied from the line that already serves production."""
    p = settings.server.davfs_secrets
    lines = p.read_text(encoding="utf-8").splitlines() if p.exists() else []
    if any(l.split() and l.split()[0] == dav_url for l in lines):
        return
    base = settings.server.dav_base
    donor = next((l for l in lines if l.split() and l.split()[0].startswith(base + "/")), None)
    if not donor:
        raise OpsError(f"no line for {base}/… in {p} to take the runner's credentials from")
    _, user, secret = donor.split(None, 2)
    lines.append(f"{dav_url} {user} {secret}")
    p.write_text("\n".join(lines) + "\n", encoding="utf-8"); p.chmod(0o600)
    log.info("davfs2 secret added for %s", dav_url)


def install(settings: Settings, env: Env, dav_url: str) -> dict[str, str]:
    s, names = settings.server, unit_names(env)
    d = env.dir(s)
    ws = d / "home" / "ChrisBuilds64"
    env.mount.mkdir(parents=True, exist_ok=True)
    ensure_davfs_secret(settings, env, dav_url)

    units = {
        names["mount"]: _render("mount.mount", what=dav_url, where=env.mount, user=s.runner_user, label=env.label),
        names["cockpit"]: _render("cockpit.service", env=env.name, label=env.label, dir=d, mount_unit=names["mount"], user=s.runner_user),
        names["runner"]: _render("runner.service", env=env.name, label=env.label, dir=d, home=d / "home", ws=ws,
                                 mount_unit=names["mount"], user=s.runner_user, data=env.mount / "flow",
                                 claude=s.claude_bin, env_file=s.runner_env_file,
                                 pull=f"{s.shared / 'canon'},{s.shared / 'control'}", shared=s.shared),
    }
    for name, text in units.items():
        p = SYSTEMD / name
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8"); p.chmod(0o644)
            log.info("unit written: %s", name)
    run(["systemctl", "daemon-reload"])

    if env.is_root:
        # the root stage takes over the port and the mount the single-stage units held
        for legacy in LEGACY_UNITS:
            if run(["systemctl", "is-enabled", legacy], check=False, quiet=True).returncode == 0 or \
               run(["systemctl", "is-active", legacy], check=False, quiet=True).returncode == 0:
                run(["systemctl", "disable", "--now", legacy], check=False)
                log.info("legacy unit stopped and disabled: %s", legacy)
    for key in ("mount", "cockpit", "runner"):
        run(["systemctl", "enable", "--now", names[key]])
        run(["systemctl", "restart", names[key]])
    return names


def status(settings: Settings) -> list[dict]:
    rows = []
    for env in settings.envs.values():
        names = unit_names(env)
        row = {"stage": env.name, "port": env.port, "path": env.base_path or "/"}
        for key, unit in names.items():
            row[key] = run(["systemctl", "is-active", unit], check=False, quiet=True).stdout.strip() or "?"
        rows.append(row)
    return rows


def nginx_snippet(settings: Settings) -> str:
    """All prefixed stages as location blocks. The root stage is the vhost's own `location /`."""
    blocks = [_render("nginx-location.conf", base_path=e.base_path, port=e.port, label=e.label)
              for e in settings.envs.values() if not e.is_root]
    head = ("# Generated by pressroom-env — one location per staged PressRoom (TEST, ENTW). The root is PROD and\n"
            "# stays the vhost's own `location /`. The vhost includes this file once:\n"
            f"#   include {settings.server.nginx_snippet};\n\n")
    return head + "\n".join(blocks)


def install_nginx(settings: Settings) -> bool:
    """Write the snippet; reload nginx only when it changed and the configuration tests clean."""
    p = settings.server.nginx_snippet
    text = nginx_snippet(settings)
    if p.exists() and p.read_text(encoding="utf-8") == text:
        return False
    p.write_text(text, encoding="utf-8"); p.chmod(0o644)
    run(["nginx", "-t"])
    run(["systemctl", "reload", "nginx"])
    log.info("nginx snippet written and nginx reloaded: %s", p)
    return True


def vhost_includes_snippet(settings: Settings, vhost: Path) -> bool:
    if not vhost.exists():
        return False
    return re.search(rf"^\s*include\s+{re.escape(str(settings.server.nginx_snippet))};", vhost.read_text(encoding="utf-8"), re.M) is not None
