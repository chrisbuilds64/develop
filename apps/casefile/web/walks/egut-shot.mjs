// The e-report world: list, the case that waits for you, the reader on the report, the rulebook, the board; then the path: approve → letter drafted. usage: node egut-shot.mjs <base> <outdir>
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
const [base, out] = process.argv.slice(2);
const PFX = process.env.BASE_PATH || "";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const issues = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, baseURL: base, ignoreHTTPSErrors: true, locale: "de-DE" });
const page = await ctx.newPage();
page.on("pageerror", (e) => issues.push(e.message));
page.on("console", (m) => { if (m.type() === "error") issues.push(`console: ${m.text().slice(0, 160)}`); });
page.on("response", (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await page.request.post(PFX + "/api/demo/session", { data: { world: "egutachten" } });
const CASE = "KH-2026-1182-auffahrunfall-a3-kleinwagen";
await page.goto(`${PFX}/case/${CASE}`, { waitUntil: "networkidle" });
await page.waitForTimeout(800);
await page.screenshot({ path: join(out, "1-case.png") });
console.log("stub:", await page.locator(".case-head .stub").innerText(), "| button:", await page.locator(".foot .btn").innerText());
await page.getByRole("button", { name: /^Gutachten/ }).first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "2-reader.png") });
await page.keyboard.press("Escape");
await page.goto(`${PFX}/rules`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "3-rules.png") });
await page.goto(`${PFX}/board`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "4-board.png") });
await page.goto(`${PFX}/case/${CASE}`, { waitUntil: "networkidle" });
await page.locator(".foot .btn").click();
await page.waitForTimeout(6500);
console.log("after approve:", await page.locator(".case-head .stub").innerText(), "| files:", (await page.locator(".desk-grid .file .name").allInnerTexts()).join(", "));
await page.screenshot({ path: join(out, "5-after-approve.png") });
await page.getByRole("button", { name: /^Anschreiben/ }).first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "6-letter.png") });
await ctx.close(); await browser.close();
console.log(`ISSUES (${issues.length}): ${issues.join("; ") || "none"}`);
