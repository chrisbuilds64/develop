// Where the AI helps: the patterns view, the photo hints at inspection, the total-loss pre-check. usage: node ai-shot.mjs <base> <outdir>
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
const [base, out] = process.argv.slice(2);
const PFX = process.env.BASE_PATH || "";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const issues = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, baseURL: base, ignoreHTTPSErrors: true, locale: "de-DE" });
const page = await ctx.newPage();
page.on("pageerror", (e) => issues.push(e.message));
page.on("console", (m) => { if (m.type() === "error") issues.push(`console: ${m.text().slice(0, 160)}`); });
page.on("response", (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await page.request.post(PFX + "/api/demo/session", { data: { world: "egutachten" } });
await page.goto(`${PFX}/signals`, { waitUntil: "networkidle" });
await page.waitForTimeout(700);
console.log("signals:", (await page.locator(".signal h2").allInnerTexts()).join(" | "));
await page.screenshot({ path: join(out, "1-signals.png") });
await page.locator(".signal .card").first().click();
await page.waitForTimeout(600);
console.log("case from signal:", await page.locator(".case-head h1").innerText());
await page.goto(`${PFX}/case/KK-2026-1190-parkschaden-tiefgarage`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "2-hints.png") });
await page.goto(`${PFX}/case/KK-2026-1198-frontalschaden-kleinwagen`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
console.log("total loss:", await page.locator(".case-head .stub").innerText(), "| btn:", await page.locator(".foot .btn").innerText());
await page.screenshot({ path: join(out, "3-total.png") });
await page.getByRole("button", { name: /^Prüfbericht/ }).first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "4-total-report.png") });
await page.goto(`${PFX}/rules`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.locator(".rules-scroll").evaluate((e) => { e.scrollTop = 900; });
await page.waitForTimeout(300);
await page.screenshot({ path: join(out, "5-rules-connectors.png") });
await page.request.post(PFX + "/api/demo/session", { data: { world: "claims" } });
await page.goto(`${PFX}/signals`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
console.log("claims signals:", (await page.locator(".signal h2").allInnerTexts()).join(" | "));
await page.screenshot({ path: join(out, "6-claims-signals.png") });
await ctx.close(); await browser.close();
console.log(`ISSUES (${issues.length}): ${issues.join("; ") || "none"}`);
