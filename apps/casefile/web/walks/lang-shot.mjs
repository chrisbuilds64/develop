// The language switch: the claims world in English, the PressRoom in German. usage: node lang-shot.mjs <base> <outdir>
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
const [base, out] = process.argv.slice(2);
const PFX = process.env.BASE_PATH || "";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const issues = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, baseURL: base, ignoreHTTPSErrors: true, locale: "de-DE" });
const page = await ctx.newPage();
page.on("pageerror", (e) => issues.push(e.message));
page.on("response", (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await page.request.post(PFX + "/api/demo/session", { data: { world: "claims" } });
await page.goto(`${PFX}/case/HR-2026-0417-wasserschaden-badezimmer`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "English" }).click();
await page.waitForTimeout(900);
console.log("claims after switch:", await page.locator(".case-head .stub").innerText(), "|", await page.locator(".list h2").innerText(), "| html lang:", await page.evaluate(() => document.documentElement.lang));
await page.screenshot({ path: join(out, "claims-en.png") });
await page.request.post(PFX + "/api/demo/session", { data: { world: "pressroom" } });
await page.goto(`${PFX}/board`, { waitUntil: "networkidle" });
await page.waitForTimeout(500);
console.log("pressroom board first column:", await page.locator(".col h3 span").first().innerText(), "| menu:", await page.locator(".views .view.on").innerText());
await page.getByRole("button", { name: "Deutsch" }).click();
await page.waitForTimeout(900);
console.log("pressroom after switch:", await page.locator(".col h3 span").first().innerText(), "|", await page.locator(".views .view.on").innerText());
await page.screenshot({ path: join(out, "pressroom-de.png") });
await page.reload({ waitUntil: "networkidle" });
console.log("sticks after reload:", await page.locator(".views .view.on").innerText());
await ctx.close(); await browser.close();
console.log(`ISSUES (${issues.length}): ${issues.join("; ") || "none"}`);
