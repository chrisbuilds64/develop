// The seeded worlds on the surface. usage: node seed-shot.mjs <base> <outdir>
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
const [base, out] = process.argv.slice(2);
const PFX = process.env.BASE_PATH || "";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const issues = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, baseURL: base, ignoreHTTPSErrors: true, locale: "de-DE" });
const page = await ctx.newPage();
page.on("pageerror", (e) => issues.push(e.message));
page.on("console", (m) => { if (m.type() === "error") issues.push(`console: ${m.text()}`); });
page.on("response", (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await page.request.post(PFX + "/api/demo/session", { data: { world: "claims" } });
await page.goto(`${PFX}/case/HR-2026-0417-wasserschaden-badezimmer`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "claims-0417.png") });
await page.getByRole("button", { name: /^Foto 2/ }).first().click();
await page.waitForTimeout(700);
await page.screenshot({ path: join(out, "claims-0417-photo.png") });
await page.keyboard.press("Escape");
await page.goto(`${PFX}/case/HR-2026-0512-kuechenbrand-mehrfamilienhaus`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "claims-0512.png") });
// the demo path still works: sample invoice in, reconcile plays, approve
await page.goto(`${PFX}/case/HR-2026-0417-wasserschaden-badezimmer`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Beispiel einlegen/ }).click();
await page.waitForTimeout(7000);
const stub = await page.locator(".case-head .stub").innerText();
console.log("after sample + replay:", stub);
await page.screenshot({ path: join(out, "claims-0417-after.png") });
await page.request.post(PFX + "/api/demo/session", { data: { world: "pressroom" } });
await page.goto(PFX + "/", { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "pressroom-list.png") });
await page.goto(`${PFX}/case/POD-014-stop-waiting-for-the-next-system`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, "pressroom-pod014.png") });
await page.getByRole("button", { name: /^Script/ }).first().click();
await page.waitForTimeout(800);
await page.screenshot({ path: join(out, "pressroom-pod014-reader.png") });
await ctx.close(); await browser.close();
console.log(`ISSUES (${issues.length}): ${issues.join("; ") || "none"}`);
