// The fixed head: scroll the desk and the conversation to the bottom, the title and the line must still be there. usage: node scroll-shot.mjs <base> <outdir>
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
const [base, out] = process.argv.slice(2);
const PFX = process.env.BASE_PATH || "";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const issues = [];
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 }, baseURL: base, ignoreHTTPSErrors: true, locale: "de-DE" });
const page = await ctx.newPage();
page.on("pageerror", (e) => issues.push(e.message));
page.on("response", (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await page.request.post(PFX + "/api/demo/session", { data: { world: "claims" } });
await page.goto(PFX + "/case/HR-2026-0417-wasserschaden-badezimmer", { waitUntil: "networkidle" });
await page.waitForTimeout(500);
const h1 = page.locator("h1");
console.log("thread scrolled to bottom on load:", await page.locator(".thread-scroll").evaluate((e) => Math.abs(e.scrollHeight - e.scrollTop - e.clientHeight) < 4));
await page.locator(".desk").evaluate((e) => { e.scrollTop = 1e6; });
await page.locator(".thread-scroll").evaluate((e) => { e.scrollTop = 0; });
await page.waitForTimeout(300);
console.log("h1 visible after scrolling:", await h1.isVisible(), "y:", (await h1.boundingBox())?.y);
console.log("button visible:", await page.getByRole("button", { name: /Freigeben/ }).isVisible());
await page.screenshot({ path: join(out, "scrolled.png") });
await page.getByRole("button", { name: /^Schadenmeldung/ }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: join(out, "reader.png") });
await ctx.close(); await browser.close();
console.log(`ISSUES (${issues.length}): ${issues.join("; ") || "none"}`);
