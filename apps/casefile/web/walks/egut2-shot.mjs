// The follow-up case (version 2 of the report, reader with version chips) and the pre-check that finishes on its own. usage: node egut2-shot.mjs <base> <outdir>
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
const [base, out] = process.argv.slice(2);
const PFX = process.env.BASE_PATH || "";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const issues = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, baseURL: base, ignoreHTTPSErrors: true, locale: "de-DE" });
const page = await ctx.newPage();
page.on("pageerror", (e) => issues.push(e.message));
page.on("response", (r) => { if (r.status() >= 400) issues.push(`${r.status()} ${r.url()}`); });
await page.request.post(PFX + "/api/demo/session", { data: { world: "egutachten" } });
await page.goto(`${PFX}/case/KK-2026-0902-wildunfall-landstrasse`, { waitUntil: "networkidle" });
await page.waitForTimeout(600);
await page.getByRole("button", { name: /^Gutachten/ }).first().click();
await page.waitForTimeout(600);
console.log("versions:", (await page.locator(".reader-meta .versions [role=tab]").allInnerTexts()).join(" | "));
await page.screenshot({ path: join(out, "7-v2.png") });
await page.goto(`${PFX}/case/KK-2026-1203-hagelschaden-pkw`, { waitUntil: "networkidle" });
await page.waitForTimeout(7000);
console.log("hail after replay:", await page.locator(".case-head .stub").innerText());
await page.screenshot({ path: join(out, "8-hail.png") });
await page.goto(`${PFX}/list`, { waitUntil: "networkidle" });
await page.waitForTimeout(500);
await page.screenshot({ path: join(out, "9-list.png") });
await ctx.close(); await browser.close();
console.log(`ISSUES (${issues.length}): ${issues.join("; ") || "none"}`);
